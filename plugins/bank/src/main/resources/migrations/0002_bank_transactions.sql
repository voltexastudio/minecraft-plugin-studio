-- Bank v1 contract: append-only transaction ledger. Every deposit and
-- withdraw is recorded with the resulting balance (balance_after).
-- amount is a positive magnitude; the sign is carried by type.
CREATE TABLE IF NOT EXISTS bank_transactions (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    type VARCHAR(16) NOT NULL,
    amount BIGINT NOT NULL,
    balance_after BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_bank_transactions_account FOREIGN KEY (account_id) REFERENCES bank_accounts (account_id),
    CONSTRAINT ck_bank_transactions_type CHECK (type IN ('DEPOSIT', 'WITHDRAW')),
    CONSTRAINT ck_bank_transactions_amount CHECK (amount > 0),
    CONSTRAINT ck_bank_transactions_balance_after CHECK (balance_after >= 0)
);
