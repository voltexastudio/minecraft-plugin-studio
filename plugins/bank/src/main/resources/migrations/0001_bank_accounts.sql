-- Bank v1 contract: player bank accounts. One account per player
-- (owner_uuid unique); the display name is denormalized for listings.
-- Balance is stored in the smallest currency unit (integer, never
-- floating point).
CREATE TABLE IF NOT EXISTS bank_accounts (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_uuid VARCHAR(36) NOT NULL,
    owner_name VARCHAR(16) NOT NULL,
    balance BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_bank_accounts_owner_uuid UNIQUE (owner_uuid),
    CONSTRAINT ck_bank_accounts_balance CHECK (balance >= 0)
);
